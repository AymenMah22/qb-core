-- Daily Activity Report
SELECT 
  DATE(heist_timestamp) as date,
  COUNT(*) as total_heists,
  SUM(CASE WHEN success = 1 THEN 1 ELSE 0 END) as successful,
  SUM(CASE WHEN success = 0 THEN 1 ELSE 0 END) as failed,
  SUM(final_payout) as total_payout,
  COUNT(DISTINCT leader_citizenid) as unique_leaders
FROM cargo_heist_history
WHERE heist_timestamp >= DATE_SUB(NOW(), INTERVAL 7 DAY)
GROUP BY DATE(heist_timestamp)
ORDER BY date DESC;

-- Player Activity Report (individual)
SELECT 
  h.citizenid,
  h.heat_level,
  h.total_heists,
  h.successful_heists,
  h.failed_heists,
  ROUND((h.successful_heists / h.total_heists * 100), 2) as success_rate,
  h.total_earned,
  h.last_heist,
  c.cooldown_until
FROM cargo_heist_heat h
LEFT JOIN cargo_heist_cooldowns c ON h.citizenid = c.citizenid
WHERE h.citizenid = 'ABC12345';

-- Economic Impact Report (last 7 days)
SELECT 
  'Last 7 Days' as period,
  COUNT(*) as total_heists,
  SUM(CASE WHEN success = 1 THEN 1 ELSE 0 END) as successful,
  SUM(final_payout) as money_generated,
  ROUND(AVG(final_payout), 0) as avg_payout,
  COUNT(DISTINCT leader_citizenid) as unique_players
FROM cargo_heist_history
WHERE heist_timestamp >= DATE_SUB(NOW(), INTERVAL 7 DAY);

