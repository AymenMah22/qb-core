-- Fastest completion times
SELECT 
  citizenid,
  player_name,
  fastest_completion as seconds,
  CONCAT(FLOOR(fastest_completion / 60), 'm ', MOD(fastest_completion, 60), 's') as time_formatted
FROM cargo_heist_leaderboard
WHERE fastest_completion < 999999
ORDER BY fastest_completion ASC
LIMIT 10;

-- Most active pilots
SELECT 
  citizenid,
  player_name,
  times_as_pilot,
  air_heists,
  total_earned
FROM cargo_heist_leaderboard
WHERE times_as_pilot > 0
ORDER BY times_as_pilot DESC
LIMIT 10;

-- Best success rates (minimum 10 heists)
