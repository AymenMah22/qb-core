WHERE citizenid = 'ABC12345';

-- View all banned players (full schema only)
SELECT * FROM cargo_heist_blacklist WHERE is_active = 1;

-- ============================================================================
-- HEIST MONITORING
-- ============================================================================

-- View currently active heists (full schema only)
SELECT 
  heist_id,
  leader_citizenid,
  cargo_id,
  approach_method,
  status,
  cargo_condition,
  TIMESTAMPDIFF(MINUTE, started_at, NOW()) as duration_minutes
FROM cargo_heist_active
WHERE status NOT IN ('completed', 'failed');

-- View available cargo
SELECT 
  cargo_id,
  cargo_type,
  current_value,
  security_level,
  is_active,
  is_claimed,
  available_end
FROM cargo_heist_intel
WHERE is_active = 1 AND is_claimed = 0
ORDER BY available_end ASC;

-- View recent heist completions (last 24 hours)
SELECT 
  heist_id,
  leader_citizenid,
  cargo_type,
  approach_method,
  success,
  final_payout,
  completion_time,
  heist_timestamp
FROM cargo_heist_history
WHERE heist_timestamp > DATE_SUB(NOW(), INTERVAL 24 HOUR)
ORDER BY heist_timestamp DESC;

-- Count heists by success/failure today
SELECT 
  success,
  COUNT(*) as count,
  SUM(final_payout) as total_payout
FROM cargo_heist_history
WHERE DATE(heist_timestamp) = CURDATE()
GROUP BY success;

-- ============================================================================
-- STATISTICS & ANALYTICS
-- ============================================================================

-- Top 10 earners (all time)
SELECT 
  h.citizenid,
  h.total_earned,
  h.total_heists,
  h.successful_heists,
  ROUND((h.successful_heists / h.total_heists * 100), 2) as success_rate
FROM cargo_heist_heat h
ORDER BY h.total_earned DESC
LIMIT 10;

-- Most popular cargo types
SELECT 
  cargo_type,
  COUNT(*) as times_attempted,
  SUM(CASE WHEN success = 1 THEN 1 ELSE 0 END) as times_successful,
  ROUND(AVG(final_payout), 0) as avg_payout
FROM cargo_heist_history
GROUP BY cargo_type
ORDER BY times_attempted DESC;

-- Ground vs Air approach statistics
SELECT 
  approach_method,
  COUNT(*) as total_attempts,
  SUM(CASE WHEN success = 1 THEN 1 ELSE 0 END) as successful,
  ROUND(AVG(final_payout), 0) as avg_payout,
  ROUND(AVG(completion_time), 0) as avg_time_seconds
FROM cargo_heist_history
GROUP BY approach_method;

-- Heist activity by hour of day
SELECT 
  HOUR(heist_timestamp) as hour_of_day,
  COUNT(*) as heist_count
FROM cargo_heist_history
WHERE heist_timestamp > DATE_SUB(NOW(), INTERVAL 7 DAY)
GROUP BY HOUR(heist_timestamp)
ORDER BY hour_of_day;

-- Total money generated by heists
SELECT 
  SUM(final_payout) as total_money_paid,
  COUNT(*) as total_heists,
  ROUND(AVG(final_payout), 0) as avg_payout
FROM cargo_heist_history
WHERE success = 1;

-- Players with highest heat levels
SELECT 
  citizenid,
  heat_level,
  total_heists,
  last_heist
FROM cargo_heist_heat
WHERE heat_level > 0
ORDER BY heat_level DESC, total_heists DESC
LIMIT 20;

-- ============================================================================
-- ECONOMY BALANCING
-- ============================================================================

-- Average payout by cargo type and approach
SELECT 
  cargo_type,
  approach_method,
  COUNT(*) as attempts,
  ROUND(AVG(final_payout), 0) as avg_payout,
  MIN(final_payout) as min_payout,
  MAX(final_payout) as max_payout
FROM cargo_heist_history
WHERE success = 1
GROUP BY cargo_type, approach_method
ORDER BY cargo_type, approach_method;

-- Success rates by security level
SELECT 
  ci.security_level,
  COUNT(*) as attempts,
  SUM(CASE WHEN hh.success = 1 THEN 1 ELSE 0 END) as successful,
  ROUND((SUM(CASE WHEN hh.success = 1 THEN 1 ELSE 0 END) / COUNT(*) * 100), 2) as success_rate
FROM cargo_heist_history hh
JOIN cargo_heist_intel ci ON hh.cargo_id = ci.cargo_id
GROUP BY ci.security_level
ORDER BY ci.security_level;

-- Intel acquisition methods (full schema only)
SELECT 
  intel_source,
  COUNT(*) as times_used,
  ROUND(AVG(intel_quality), 2) as avg_quality,
  ROUND(AVG(cost_paid), 0) as avg_cost
FROM cargo_heist_intel_acquired
GROUP BY intel_source
ORDER BY times_used DESC;

-- ============================================================================
-- MAINTENANCE & CLEANUP
-- ============================================================================

-- Clean up expired cargo intel manually
UPDATE cargo_heist_intel
SET is_active = 0
WHERE available_end < NOW() AND is_active = 1;

-- Delete very old cargo intel (older than 7 days)
DELETE FROM cargo_heist_intel
WHERE available_end < DATE_SUB(NOW(), INTERVAL 7 DAY);

-- Clean up expired cooldowns
DELETE FROM cargo_heist_cooldowns 
WHERE cooldown_until < NOW();

-- Delete old heist history (older than 30 days)
DELETE FROM cargo_heist_history 
WHERE heist_timestamp < DATE_SUB(NOW(), INTERVAL 30 DAY);

-- Clean up old intel acquisition records (full schema only)
DELETE FROM cargo_heist_intel_acquired
WHERE expires_at < DATE_SUB(NOW(), INTERVAL 7 DAY);

-- Manually decay heat for all players
UPDATE cargo_heist_heat
SET heat_level = GREATEST(0, heat_level - 1)
WHERE heat_level > 0;

-- Reset all cooldowns (emergency use only)
TRUNCATE TABLE cargo_heist_cooldowns;

